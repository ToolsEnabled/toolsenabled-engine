'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const MAP_PATH = path.join(ROOT, 'schemas', 'ownership-map.json');
const OUTPUTS = Object.freeze({
  typescript: path.join(ROOT, 'schemas', 'generated', 'ownership-map.types.ts'),
  python: path.join(ROOT, 'schemas', 'generated', 'ownership_map_types.py')
});

function map() {
  return JSON.parse(fs.readFileSync(MAP_PATH, 'utf8'));
}

function validate(source) {
  if (!source || source.schemaVersion !== 1 || source.contractVersion !== 'coordinator-cross-repo-v1') {
    throw new Error('ownership-map.json must use schemaVersion 1 and coordinator-cross-repo-v1.');
  }
  const domains = new Set();
  for (const item of source.owners || []) {
    if (!item || typeof item.domain !== 'string' || typeof item.owner !== 'string' || domains.has(item.domain)) {
      throw new Error('ownership-map.json must assign each domain exactly one owner.');
    }
    domains.add(item.domain);
  }
  for (const required of ['task', 'evidence', 'context', 'provider', 'finance', 'ui', 'model-runtime', 'tool-forge']) {
    if (!domains.has(required)) throw new Error(`ownership-map.json is missing owner for ${required}.`);
  }
  return source;
}

function ownerObject(source) {
  return Object.fromEntries(source.owners.map(item => [item.domain, item.owner]));
}

function renderTypeScript(source) {
  const domains = source.owners.map(item => `'${item.domain}'`).join(' | ');
  const ownership = JSON.stringify(ownerObject(source), null, 2);
  return `// Generated by tools/generate-ownership-types.js from schemas/ownership-map.json. Do not edit.\n`
    + `export const OWNERSHIP_MAP_SCHEMA_VERSION = ${source.schemaVersion} as const;\n`
    + `export const OWNERSHIP_CONTRACT_VERSION = '${source.contractVersion}' as const;\n\n`
    + `export type OwnershipDomain = ${domains};\n`
    + `export type OwnershipOwner = 'toolsenabled' | 'portfolio-dashboard';\n\n`
    + `export const OWNERS_BY_DOMAIN: Readonly<Record<OwnershipDomain, OwnershipOwner>> = Object.freeze(${ownership} as Record<OwnershipDomain, OwnershipOwner>);\n`;
}

function renderPython(source) {
  const ownership = JSON.stringify(ownerObject(source), null, 2);
  return `# Generated by tools/generate-ownership-types.js from schemas/ownership-map.json. Do not edit.\n`
    + `OWNERSHIP_MAP_SCHEMA_VERSION = ${source.schemaVersion}\n`
    + `OWNERSHIP_CONTRACT_VERSION = '${source.contractVersion}'\n`
    + `OWNERS_BY_DOMAIN: dict[str, str] = ${ownership}\n`;
}

function generatedFiles(source = validate(map())) {
  return new Map([[OUTPUTS.typescript, renderTypeScript(source)], [OUTPUTS.python, renderPython(source)]]);
}

function generate({ check = false } = {}) {
  const files = generatedFiles();
  for (const [target, content] of files) {
    if (check) {
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
        throw new Error(`Generated ownership contract is stale: ${path.relative(ROOT, target)}`);
      }
    } else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, content, 'utf8');
    }
  }
  return files;
}

if (require.main === module) {
  generate({ check: process.argv.includes('--check') });
  process.stdout.write(`Ownership contract ${process.argv.includes('--check') ? 'verified' : 'generated'}.\n`);
}

module.exports = { MAP_PATH, OUTPUTS, generate, generatedFiles, renderPython, renderTypeScript, validate };
